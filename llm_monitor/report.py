"""RESULTS.md tables and figures from the evaluate.py results (no model fitting here)."""
from __future__ import annotations

import os

import numpy as np

LABEL = {"clock": "clock (t only)", "pairwise": "feature pairwise monitor", "edge_monitor": "per-edge monitor (max)",
         "bag": "bag-of-edges", "bag+graph": "bag + graph", "oracle": "oracle count + clock (not observable)"}


def name(n):
    if n in LABEL:
        return LABEL[n]
    if ":" in n:
        k, v = n.split(":", 1)
        kk = {"zs": "zero-shot", "zs1": "zero-shot, 1 sample", "lr": "stacked LR", "hgb": "stacked HGB",
              "ext": "external"}.get(k, k)
        return f"{v} ({kk})"
    return n


def f3(x):
    return "–" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.3f}"


def ci(m, k):
    c = m.get(f"{k}_ci")
    return f"{f3(m.get(k))} [{f3(c[0])}, {f3(c[1])}]" if c else f3(m.get(k))


def order(names):
    refs = [n for n in LABEL if n in names]
    rest = [n for n in names if n not in LABEL]
    rest.sort(key=lambda n: (n.split(":", 1)[-1], ["zs", "zs1", "lr", "hgb", "ext"].index(n.split(":")[0])
                             if n.split(":")[0] in ("zs", "zs1", "lr", "hgb", "ext") else 9))
    return refs + rest


def write_report(out, res_a, res_b, cost, D, preds, variants):
    L = ["# LLM communication-monitor baselines: results", "",
         "Generated by `python -m llm_monitor.evaluate` (deterministic; no API calls). Target `tip` = tip within Δ = 3 "
         "rounds (θ = 8), defined while count_t < θ. CIs: bootstrap over configs (1000×). Thresholds for recall@5 % "
         "FPR: (a) from the same OOF predictions, (b) frozen from train+val OOF.", ""]
    L += [f"## Protocol (a): pooled OOF over all night configs", "",
          f"{res_a['rows']} tip rows from {res_a['configs']} configs; CIs and paired differences on the "
          f"{res_a['rows_common']} rows that every predictor covers. GroupKFold(5) by config, 3 seeds (AUROC = mean "
          "over seeds of the seed-averaged OOF score for fitted models).", "",
          "| Predictor | AUROC [95 % CI] | AUPRC [95 % CI] | R@5%FPR | Brier | n | pos |", "|---|---|---|---|---|---|---|"]
    for n in order(res_a["main"]):
        m = res_a["main"][n]
        L.append(f"| {name(n)} | {ci(m, 'auroc')} | {ci(m, 'auprc')} | {f3(m.get('recall_at_5fpr'))} | "
                 f"{f3(m.get('brier'))} | {m.get('n')} | {m.get('n_pos')} |")
    L += ["", "Zero-shot Brier after cross-fitted isotonic calibration.", ""]
    # paired diffs
    L += ["### Paired AUROC differences (protocol a, same rows and draws)", "", "| Difference | mean | 95 % CI | P(Δ ≤ 0) |",
          "|---|---|---|---|"]
    for k, d in res_a["paired_diffs_common_rows"].items():
        n, metric = k.split("|")
        a, b = n.split(" - ")
        if metric != "auroc" or a in LABEL:
            continue
        L.append(f"| {name(a)} − {name(b)} | {d['mean']:+.3f} | [{d['ci'][0]:+.3f}, {d['ci'][1]:+.3f}] | {d['p_le_0']:.3f} |")
    # protocol b
    sp = list(res_b["splits"])
    L += ["", "## Protocol (b): frozen (select + threshold on train+val, evaluated once per held-out split)", ""]
    for metric in ("auroc", "auprc", "recall_at_5fpr", "brier"):
        L += [f"**{metric}**", "", "| Predictor | " + " | ".join(s.replace("night_", "") for s in sp) + " |",
              "|---|" + "---|" * len(sp)]
        names = order(res_b["splits"][sp[0]]["metrics"]) if sp else []
        for n in names:
            cells = []
            for s in sp:
                m = res_b["splits"][s]["metrics"].get(n, {})
                cells.append(ci(m, metric) if metric in ("auroc", "auprc") else f3(m.get(metric)))
            L.append(f"| {name(n)} | " + " | ".join(cells) + " |")
        L.append("")
    L += ["Rows / positives per split: " + ", ".join(
        f"{s.replace('night_', '')} {res_b['splits'][s]['metrics'].get('clock', {}).get('n')}/"
        f"{res_b['splits'][s]['metrics'].get('clock', {}).get('n_pos')}" for s in sp), ""]
    # slices
    sl = res_a["slices"]
    key = [n for n in order(res_a["main"]) if n in sl.get("risk=0", {})]
    L += ["## Slices (protocol a, AUROC on common rows)", "", "| Slice | " + " | ".join(name(n) for n in key) + " |",
          "|---|" + "---|" * len(key)]
    for s, d in sl.items():
        if s in ("time_matched_auroc", "mixed_cfg_x_time_auroc"):
            continue
        npos = next(iter(d.values())).get("n_pos")
        nn = next(iter(d.values())).get("n")
        L.append(f"| {s} (n={nn}, pos={npos}) | " + " | ".join(f3(d[n].get("auroc")) for n in key) + " |")
    L.append("| time-matched (within rounds-to-cut bins) | " + " | ".join(f3(sl["time_matched_auroc"][n]) for n in key) + " |")
    L.append("| mixed configs, within config × time bin | " + " | ".join(f3(sl["mixed_cfg_x_time_auroc"][n]) for n in key) + " |")
    # run level
    rl = res_a["run_level"]
    L += ["", "## Run level (protocol a): final `tipped` from a fixed prefix", "",
          "LLM zero-shot rows use p_tip_end; other predictors their row score at the prefix. Only runs not yet tipped "
          "at the prefix. Within-config = AUROC among replicates of mixed configs (a config-only predictor scores 0.5).", "",
          "| Predictor | cut−6 AUROC (n) | cut−6 within-config | mech+2 AUROC (n) | mech+2 within-config |", "|---|---|---|---|---|"]
    for n in key:
        a_, b_ = rl["cut-6"].get(n, {}), rl["mech+2"].get(n, {})
        L.append(f"| {name(n)} | {f3(a_.get('auroc'))} ({a_.get('n')}) | {f3(a_.get('within_config_auroc'))} | "
                 f"{f3(b_.get('auroc'))} ({b_.get('n')}) | {f3(b_.get('within_config_auroc'))} |")
    # node + count
    L += ["", "## Node level (zero-shot, protocol a): violates within Δ among agents not yet violating", "",
          "| Variant | pooled AUROC | within-snapshot AUROC | stuck: pooled | stuck: within |", "|---|---|---|---|---|"]
    for v, r in res_a["node"].items():
        if r:
            L.append(f"| {v} | {f3(r['all'].get('auroc'))} | {f3(r['all'].get('within_snapshot_auroc'))} | "
                     f"{f3(r['stuck'].get('auroc'))} | {f3(r['stuck'].get('within_snapshot_auroc'))} |")
    L += ["", "## Count (`risk_count`, MAE in agents, all night rows)", "", "| Predictor | MAE |", "|---|---|"]
    for n, r in res_a["count"].items():
        L.append(f"| {n} | {f3(r['mae'])} |")
    # lead time (frozen)
    L += ["", "## Lead time (protocol b, frozen threshold)", "",
          "| Split | Predictor | tipped runs alarmed before θ | median lead (rounds) | untipped runs with a false alarm |",
          "|---|---|---|---|---|"]
    for s in sp:
        for n in order(res_b["splits"][s]["lead_time"]):
            r = res_b["splits"][s]["lead_time"][n]
            L.append(f"| {s.replace('night_', '')} | {name(n)} | {f3(r['alarm_before_tip_share'])} of {r['tipped_runs']} | "
                     f"{f3(r['median_lead_rounds'])} | {f3(r['false_alarm_run_share'])} of {r['untipped_runs']} |")
    # cost
    L += ["", "## Cost", "", "| Variant | calls | runs | tokens / snapshot | $ / snapshot | $ / run | $ total | latency p50 / p95 (s) |",
          "|---|---|---|---|---|---|---|---|"]
    for v, c in cost.items():
        if v.startswith("_"):
            continue
        L.append(f"| {v} | {c['calls']} | {c['runs']} | {c['tokens_per_snapshot']:.0f} | {c['usd_per_snapshot']:.5f} | "
                 f"{c['usd_per_run']:.4f} | {c['cost_usd']:.2f} | {c['latency_p50']:.1f} / {c['latency_p95']:.1f} |")
    g = cost.get("_gnn_jury", {})
    if g:
        L += ["", "GNN feature cost (jury, both judges, same snapshots): " + "; ".join(
            f"{j}: {g[j]['tokens_per_snapshot']:.0f} tokens / snapshot, {g[j]['tokens_per_message']:.0f} tokens / message"
            for j in ("claude-haiku-5-5", "deepseek-v4-flash") if j in g) +
            f"; Haiku share ${g.get('haiku_usd_per_snapshot', 0):.5f} / snapshot. {g.get('note', '')}", ""]
    # reliability
    L += ["## Reliability", "", "| Variant | parse ok | refusals | mean SD of p_tip_3 over k | AUROC k=1 | AUROC k=3 |",
          "|---|---|---|---|---|---|"]
    ps = _parse_stats(D)
    for v in variants:
        r = res_a["reliability"].get(v, {})
        st = ps.get(v, {})
        okr = st["ok"] / st["all"] if st.get("all") else None
        L.append(f"| {v} | {f3(okr)} ({st.get('ok')}/{st.get('all')}) | {st.get('refusals')} | "
                 f"{f3(r.get('mean_sd_p_tip_3'))} | {f3(r.get('auroc_k1'))} | {f3(r.get('auroc_k3'))} |")
    if res_b.get("vx_shift"):
        L += ["", "## vx: paired shift effect Δ_shift (AUROC, arm − id rep0) vs Δ_noise (id rep1 − id rep0)", ""]
        arms = list(res_b["vx_shift"])
        names = order(res_b["vx_shift"][arms[0]])
        L += ["| Predictor | " + " | ".join(arms) + " |", "|---|" + "---|" * len(arms)]
        for n in names:
            L.append(f"| {name(n)} | " + " | ".join(
                f"{res_b['vx_shift'][a][n]['delta_auroc']:+.3f}" if res_b['vx_shift'][a][n]['delta_auroc'] is not None
                else "–" for a in arms) + " |")
    open(os.path.join(out, "RESULTS.md"), "w").write("\n".join(L) + "\n")
    try:
        figures(out, D, preds, res_a)
    except Exception as e:  # figures are optional
        print("figures failed:", repr(e)[:200])


def _parse_stats(D):
    import json
    f = os.path.join(D.data_dir, "_base", "parse_stats.json")
    return json.load(open(f)) if os.path.exists(f) else {}


def figures(out, D, preds, res_a):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from sklearn.metrics import precision_recall_curve, roc_curve
    fd = os.path.join(out, "figures")
    os.makedirs(fd, exist_ok=True)
    b = D.base
    v = "global_full" if "global_full" in D.var else (next(iter(D.var)) if D.var else None)
    if v:
        S = D.var[v]
        cov = S.groupby(b.episode_id.values).zs_tip.apply(lambda x: x.notna().all())
        eps = b.groupby("episode_id").agg(tipped=("tipped", "first"), tip_round=("tip_round", "first"),
                                          cut=("cut", "first"), split=("split", "first"))
        eps = eps[eps.index.isin(cov[cov].index)]
        rng = np.random.default_rng(7)
        tip = list(eps[eps.tipped == 1].index)
        non = list(eps[eps.tipped == 0].index)
        pick = list(rng.choice(tip, min(3, len(tip)), replace=False)) + list(rng.choice(non, min(3, len(non)), replace=False))
        fig, ax = plt.subplots(figsize=(7, 4))
        for e in pick:
            m = (b.episode_id == e).values
            t = b.t.values[m]
            r = eps.at[e, "tip_round"] if eps.at[e, "tipped"] else eps.at[e, "cut"]
            ax.plot(t - r, S.p_tip_3.values[m], "-" if eps.at[e, "tipped"] else "--",
                    label=f"{e} ({'tipped' if eps.at[e, 'tipped'] else 'not tipped'})", lw=1.5)
        ax.axvline(0, color="grey", lw=0.8)
        ax.set_xlabel("rounds relative to tip round (untipped: relative to cut)")
        ax.set_ylabel(f"p_tip_3 ({v}, mean of samples)")
        ax.legend(fontsize=6)
        fig.tight_layout()
        fig.savefig(os.path.join(fd, "trajectories.png"), dpi=150)
        plt.close(fig)
    rows = (~np.isnan(D.y)) & D.night.values
    show = [n for n in ("clock", "pairwise", "bag", "bag+graph", "oracle") if n in preds] + \
        [n for n in preds if n.startswith("zs:") or n in ("lr:global_full", "lr:pairwise")]
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(10, 4.2))
    colors = plt.get_cmap("tab20").colors
    for i, n in enumerate(show):
        kw = {"color": colors[i % 20], "lw": 1.2, "label": name(n), "ls": "--" if n == "oracle" else "-"}
        m = rows & ~np.isnan(preds[n])
        fpr, tpr, _ = roc_curve(D.y[m], preds[n][m])
        pr, rc, _ = precision_recall_curve(D.y[m], preds[n][m])
        a1.plot(fpr, tpr, **kw)
        a2.plot(rc, pr, **kw)
    a1.plot([0, 1], [0, 1], color="grey", lw=0.6)
    a1.axvline(0.05, color="grey", lw=0.6, ls=":")
    a1.set_xlabel("FPR"), a1.set_ylabel("TPR"), a1.set_title("ROC (protocol a, OOF)")
    a2.set_xlabel("recall"), a2.set_ylabel("precision"), a2.set_title("PR (protocol a, OOF)")
    a1.legend(fontsize=6)
    fig.tight_layout()
    fig.savefig(os.path.join(fd, "roc_pr.png"), dpi=150)
    plt.close(fig)
