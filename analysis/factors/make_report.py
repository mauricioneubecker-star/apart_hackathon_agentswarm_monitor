# ------------------------------------------------------------------ method
w("## 2. Method")
w("")
w("- **Unit of inference = config** (scenario_id). Replicates of a config share every factor and are strongly "
  f"correlated (one-way ICC of `tipped` = {icc:.2f}, configs with >= 2 runs), so each config contributes one value: "
  "its tip rate (mean of `tipped` over its 1-3 control runs). Configs are weighted equally.")
w("- **Marginal permutation test** per factor: the factor's labels are permuted across configs **within design block "
  f"(split)**, {rf['meta']['B_perm']:,} permutations. This reproduces the design: every night factor was drawn per block with "
  "fixed counts (`weighted_balanced`, independent shuffles; `generate.py` `gen_night`), model mix and tech-lead status "
  "iid. Statistic: binary factor = difference of the mean config tip rates (level - reference), two-sided p = "
  "(1 + #{|T*| >= |T|}) / (B + 1); multi-level factor = n-weighted between-level variance of the config means "
  "(equivalent to a permutation one-way ANOVA F), p = (1 + #{T* >= T}) / (B + 1).")
w("- **Restrictions**: seed type is tested in the 4 blocks where it was randomized (night_branch is all `none`, "
  "night_test_ood_seed all `external`; 96 configs). Seed = tech lead only among knower/pioneer/side_task configs "
  "(64 configs), where it was a Bernoulli(0.5) draw.")
w(f"- **Effect sizes**: tip-rate differences (percentage points, pp) or per-level rates with 95% percentile CIs from a "
  f"**config-cluster bootstrap stratified by block** ({rf['meta']['B_boot']:,} resamples of configs with replacement "
  "within each block).")
w("- **Multiplicity**: Holm over the 14 main factors (category, release_freeze, manager_push, discoverability, channels, "
  "self_merge, persistent_share, prohibition_form, n_impossible, persona_mix, sanctions, model_mix, seed_type, "
  "seed_tech_lead). Post-hoc pairwise contrasts: Holm within factor. Extra design factors (seed placement, cut, push "
  "offset, family, effective enforcement): own Holm family, exploratory.")
w(f"- **Multivariable model**: logistic regression of run-level `tipped` on all 14 factors (one-hot) plus block "
  f"dummies, {rl['n_params']} parameters, Newton-Raphson with L2 lambda = 1/C, C = 1e6 (= sklearn "
  "`LogisticRegression(C=1e6)`, checked). References: " + ", ".join(f"{k} = {v}" for k, v in rl["refs"].items()) + ". "
  "Odds-ratio CIs from the stratified config-cluster bootstrap (2,000). Because unpenalized refits separate in "
  "many resamples (below), the same resamples are also refit with **Firth's bias-reduced logistic regression**. "
  "**Adjusted randomization test** per factor: permute that factor's labels across configs within block, keep all "
  "other factors fixed, refit; statistic = likelihood-ratio (deviance drop) of the factor's columns; 10,000 "
  "permutations; exact under the sharp null because the factors were assigned independently. Holm over 14.")
w("- **Adjusted risk differences** (no separation issue): OLS of the config tip rate on the same design (112 configs, "
  "equal weights; sensitivity with run-count weights), randomization test = partial F (extra sum of squares) with the "
  "same within-block permutation, 10,000 permutations; stratified config bootstrap CIs (2,000).")
w("- Seed type in the adjusted tests is permuted jointly with tech-lead status (joint null of the seed design); "
  "tech-lead status alone is permuted within block x seed type.")
w("- **Interactions** only exploratory: 2x2 config-level cells, difference in differences (DiD) with bootstrap CI, "
  "and subgroup permutation tests (effect of A within each level of B, permuted within block; uncorrected).")
w("- **Row-level contrast**: Fisher / chi-square tests on runs and the asymptotic chi-square p of the run-level LR are "
  "shown only to illustrate why they are anti-conservative here (runs within a config are not independent). DeLong is "
  "not applicable (no AUROC in this question).")
w("")

